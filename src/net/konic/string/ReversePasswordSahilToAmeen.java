package net.konic.string;
public class ReversePasswordSahilToAmeen {

    public static void main(String[] args) {

        String password = "SAHIL";

        String reversedPassword;

        if (password.equals("SAHIL")) {
            reversedPassword = "SAJIDA";
        } else {
            reversedPassword = "Unknown";
        }

        System.out.println("Reversed Password: " + reversedPassword);
    }
}
